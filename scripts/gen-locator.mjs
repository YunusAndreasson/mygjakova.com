/**
 * Generates the Kosovo locator-map geometry for KosovoLocator.astro:
 *   node scripts/gen-locator.mjs   (or: pnpm map:locator)
 *
 * Reads the committed Kosovo boundary (scripts/data/kosovo.geojson, a Natural
 * Earth admin-0 extract — public domain), simplifies it (Douglas–Peucker),
 * projects it (equirectangular with a cos(lat) width correction so the country
 * isn't horizontally stretched at ~42.5°N), and normalises it into a small
 * SVG viewBox. City pins are projected through the SAME transform so they land
 * in the right place. The result is committed at src/lib/kosovoLocator.ts, so
 * the site renders a self-hosted, no-JS, no-tile inline SVG — no runtime fetch.
 * Re-run only if the boundary or the marker list changes.
 */
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { readFileSync, writeFileSync } from 'node:fs';

const here = dirname(fileURLToPath(import.meta.url));
const SRC = join(here, 'data', 'kosovo.geojson');
const OUT = join(here, '..', 'src', 'lib', 'kosovoLocator.ts');

// Cities pinned on the map. `role` drives the rendering (Gjakova is the
// subject; the capital is a faint orientation reference). Labels are localised
// in the component, not here — keep this geometry-only and i18n-free.
const CITIES = [
  { key: 'gjakova', role: 'subject', lng: 20.43, lat: 42.381 },
  { key: 'prishtina', role: 'reference', lng: 21.1655, lat: 42.6629 },
];

const WIDTH = 100; // viewBox width; height is derived from the projected aspect
const PAD = 3; // padding inside the viewBox, in the same units
const TOLERANCE = 0.01; // Douglas–Peucker tolerance in degrees (~1 km)

const geo = JSON.parse(readFileSync(SRC, 'utf8'));
const g = geo.geometry;
const polys = g.type === 'MultiPolygon' ? g.coordinates : [g.coordinates];

// --- equirectangular projection (lng/lat degrees → planar units) ------------
const allLat = polys.flat(2).map((p) => p[1]);
const lat0 = (Math.min(...allLat) + Math.max(...allLat)) / 2;
const kx = Math.cos((lat0 * Math.PI) / 180);
const project = ([lng, lat]) => [lng * kx, -lat]; // flip Y for screen space

// --- Douglas–Peucker line simplification ------------------------------------
const sqSegDist = (p, a, b) => {
  let [x, y] = a;
  let dx = b[0] - x;
  let dy = b[1] - y;
  if (dx !== 0 || dy !== 0) {
    const t = ((p[0] - x) * dx + (p[1] - y) * dy) / (dx * dx + dy * dy);
    if (t > 1) [x, y] = b;
    else if (t > 0) [x, y] = [x + dx * t, y + dy * t];
  }
  dx = p[0] - x;
  dy = p[1] - y;
  return dx * dx + dy * dy;
};
const simplify = (pts, tol) => {
  const tol2 = tol * tol;
  const keep = new Array(pts.length).fill(false);
  keep[0] = keep[pts.length - 1] = true;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [first, last] = stack.pop();
    let maxd = tol2;
    let idx = -1;
    for (let i = first + 1; i < last; i++) {
      const d = sqSegDist(pts[i], pts[first], pts[last]);
      if (d > maxd) {
        idx = i;
        maxd = d;
      }
    }
    if (idx !== -1) {
      keep[idx] = true;
      stack.push([first, idx], [idx, last]);
    }
  }
  return pts.filter((_, i) => keep[i]);
};

// Project + simplify every ring (outer boundary + any holes).
const rings = polys.flat().map((ring) => simplify(ring.map(project), TOLERANCE));

// --- normalise into the viewBox (same transform for outline and pins) -------
const flat = rings.flat();
const xs = flat.map((p) => p[0]);
const ys = flat.map((p) => p[1]);
const minX = Math.min(...xs);
const minY = Math.min(...ys);
const scale = (WIDTH - 2 * PAD) / (Math.max(...xs) - minX);
const height = +((Math.max(...ys) - minY) * scale + 2 * PAD).toFixed(2);
const place = ([x, y]) => [
  +((x - minX) * scale + PAD).toFixed(2),
  +((y - minY) * scale + PAD).toFixed(2),
];

const toPath = (ring) =>
  `${ring
    .map((pt, i) => {
      const [x, y] = place(pt);
      return `${i ? 'L' : 'M'}${x} ${y}`;
    })
    .join('')}Z`;
const outline = rings.map(toPath).join('');

const markers = CITIES.map(({ key, role, lng, lat }) => {
  const [x, y] = place(project([lng, lat]));
  return { key, role, x, y };
});

const pointCount = rings.reduce((n, r) => n + r.length, 0);
const banner = `// Generated by scripts/gen-locator.mjs — do not edit by hand.
// Kosovo locator geometry (boundary: Natural Earth admin-0, public domain),
// projected + simplified to ${pointCount} points. Re-run \`pnpm map:locator\`.`;

const data = `${banner}
export interface LocatorMarker {
  key: string;
  role: 'subject' | 'reference';
  x: number;
  y: number;
}

export const kosovoLocator = {
  viewBox: '0 0 ${WIDTH} ${height}',
  outline: '${outline}',
  markers: ${JSON.stringify(markers)} as LocatorMarker[],
};
`;

writeFileSync(OUT, data);
console.log('wrote', OUT, '—', pointCount, 'boundary points, viewBox 0 0', WIDTH, height);
