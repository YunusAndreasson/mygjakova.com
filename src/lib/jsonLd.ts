import type { CollectionEntry } from 'astro:content';
import { localizedPath, type Locale } from '~/i18n/utils';
import { entrySlug } from '~/lib/collections';

/**
 * Shared schema.org node builders, merged into the page `@graph` by BaseLayout
 * (which exposes a `jsonLd` prop accepting a node or array of nodes). The
 * per-place `TouristAttraction` lives in its own module, `placeJsonLd.ts`.
 *
 * Every node returns a plain object so it serialises straight to JSON-LD. The
 * `@id` fragments (`#website`, `#org`) are shared across the graph so nodes can
 * reference one another (e.g. a place's `publisher` → the Organization).
 */
type Node = Record<string, unknown>;

/**
 * Stable `@id` of the site's maker as a schema.org Person. The fragment lives on
 * the maker's own hub (andreassonphoto.com), not this site's origin, so the same
 * identity node is referenced identically across every project he builds.
 */
export const MAKER_PERSON_ID = 'https://andreassonphoto.com/#person';

/**
 * Person node for the maker (Yunus Andreasson). Its `@id` is the maker's own hub
 * fragment — identical on every site he builds — so search engines can resolve
 * the guide's `creator` to one canonical identity. `sameAs` ties his social
 * profiles to that identity (the same links rendered in the footer's follow row).
 */
export function buildPerson(): Node {
  return {
    '@type': 'Person',
    '@id': MAKER_PERSON_ID,
    name: 'Yunus Andreasson',
    alternateName: ['Jonas Yūnus Andrèasson'],
    url: 'https://andreassonphoto.com',
    sameAs: [
      'https://github.com/YunusAndreasson',
      'https://x.com/YunusAndreasson',
      'https://www.instagram.com/andreasson.photo/',
      'https://www.linkedin.com/in/yunusandreasson/',
    ],
  };
}

/**
 * Organization node representing the guide as a publisher. Referenced by `@id`
 * from the WebSite node (`publisher`) and each TouristAttraction, so the graph
 * has a single shared publisher entity. `logo` must point at a reachable raster
 * (≥112px) — generated by `scripts/gen-icons.mjs` as `public/logo.png`.
 * `creator` links to the maker Person (`buildPerson`), also in the graph.
 */
export function buildOrganization(opts: { name: string; origin: string }): Node {
  const { name, origin } = opts;
  return {
    '@type': 'Organization',
    '@id': `${origin}#org`,
    name,
    url: origin,
    logo: { '@type': 'ImageObject', url: `${origin}logo.png` },
    creator: { '@id': MAKER_PERSON_ID },
  };
}

/**
 * BreadcrumbList for the breadcrumb rich result. `trail` is the ordered list of
 * ancestor crumbs (each linked); `leaf` is the current page — emitted as the
 * final `ListItem` with a name but no `item` URL, per Google's guidance that the
 * last item represents the current page.
 */
export function buildBreadcrumbJsonLd(opts: {
  lang: Locale;
  origin: string;
  trail: { name: string; path: string }[];
  leaf: string;
}): Node {
  const { lang, origin, trail, leaf } = opts;
  return {
    '@type': 'BreadcrumbList',
    itemListElement: [
      ...trail.map((c, i) => ({
        '@type': 'ListItem',
        position: i + 1,
        name: c.name,
        item: new URL(localizedPath(lang, c.path), origin).href,
      })),
      { '@type': 'ListItem', position: trail.length + 1, name: leaf },
    ],
  };
}

/**
 * CollectionPage + ItemList for the Places index — tells search engines the
 * page is a curated list of attractions, each linking to its guide.
 */
export function buildPlacesItemList(opts: {
  places: CollectionEntry<'places'>[];
  lang: Locale;
  origin: string;
  /** Canonical URL of the index page itself. */
  url: string;
  name: string;
}): Node {
  const { places, lang, origin, url, name } = opts;
  return {
    '@type': 'CollectionPage',
    name,
    url,
    isPartOf: { '@id': `${origin}#website` },
    mainEntity: {
      '@type': 'ItemList',
      numberOfItems: places.length,
      itemListElement: places.map((p, i) => ({
        '@type': 'ListItem',
        position: i + 1,
        name: p.data.title,
        url: new URL(localizedPath(lang, `/places/${entrySlug(p.id)}`), origin).href,
      })),
    },
  };
}

/**
 * CollectionPage + ItemList for the timeline — an ordered set of historical
 * milestones. Events are not individual pages, so each `ListItem` carries a name
 * only (no URL). This is semantic structure, not an `Event` rich result:
 * historical events don't qualify for Google's event results, so modelling them
 * as `Event` would be misleading markup.
 */
export function buildTimelineItemList(opts: {
  events: CollectionEntry<'timeline'>[];
  origin: string;
  url: string;
  name: string;
}): Node {
  const { events, origin, url, name } = opts;
  return {
    '@type': 'CollectionPage',
    name,
    url,
    isPartOf: { '@id': `${origin}#website` },
    mainEntity: {
      '@type': 'ItemList',
      numberOfItems: events.length,
      itemListOrder: 'https://schema.org/ItemListOrderAscending',
      itemListElement: events.map((e, i) => ({
        '@type': 'ListItem',
        position: i + 1,
        name: e.data.displayDate ? `${e.data.displayDate} — ${e.data.title}` : e.data.title,
      })),
    },
  };
}
